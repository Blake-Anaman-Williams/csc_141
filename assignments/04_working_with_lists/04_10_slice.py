Animals = ["cat", "dog", "Lion", "turtle", "elephant", "frog"]
print("The first three animals in the list are:")
print(Animals[0:3])

print('Three items from the middle of the list are:')
print(Animals[1:4])

print("The last three items in the list are:")
print(Animals[-3:])